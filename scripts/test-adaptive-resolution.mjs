import assert from 'node:assert/strict';
import { adaptResolution, resolutionCeiling } from '../src/performance/adaptiveResolution.ts';
const ceiling = resolutionCeiling(916, 1201, 2, 2, 2_500_000);
assert.ok(916 * 1201 * ceiling ** 2 <= 2_500_001);
assert.equal(resolutionCeiling(390, 844, 1, 1.5, 1_500_000), 1);
let state = { dpr: ceiling, slow: 0, fast: 0 };
state = adaptResolution(state, 10, 60, ceiling);
assert.equal(state.dpr, ceiling, 'one stalled sample must not downgrade');
state = adaptResolution(state, 10, 60, ceiling);
assert.ok(state.dpr < ceiling, 'sustained overload reduces pixels');
for (let i = 0; i < 40; i++) state = adaptResolution(state, 10, 60, ceiling);
assert.equal(state.dpr, 0.75, 'protect a readable lower bound');
for (let i = 0; i < 9; i++) state = adaptResolution(state, 60, 60, ceiling);
assert.equal(state.dpr, 0.75, 'avoid rapid quality oscillation');
state = adaptResolution(state, 60, 60, ceiling);
assert.ok(state.dpr > 0.75, 'recover after sustained healthy rendering');
assert.deepEqual(adaptResolution(state, NaN, 60, ceiling), state);
assert.ok(adaptResolution(state, 60, 60, 0.6).dpr <= 0.6, 'resize respects new ceiling');
console.log('Adaptive resolution: 8 checks passed');
